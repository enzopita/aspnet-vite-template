// state kept outside the working tree (inside .git, never committed)

export function stateFile(cwd, name) {
  const dir = join(gitDir(cwd), "app-agents");
  mkdirSync(dir, { recursive: true });
  return join(dir, name);
}

export function readState(cwd, name) {
  try {
    return JSON.parse(readFileSync(stateFile(cwd, name), "utf8"));
  } catch {
    return undefined;
  }
}

export function writeState(cwd, name, value) {
  writeFileSync(stateFile(cwd, name), `${JSON.stringify(value, null, 2)}\n`);
}

export const sha256 = (s) => createHash("sha256").update(s).digest("hex");
