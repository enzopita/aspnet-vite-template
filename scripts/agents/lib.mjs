// globs and paths

const globCache = new Map();

export function globToRegExp(glob) {
  let re = globCache.get(glob);
  if (re) return re;
  let src = "";
  for (let i = 0; i < glob.length; i++) {
    const c = glob[i];
    if (c === "*" && glob[i + 1] === "*") {
      if (glob[i + 2] === "/") {
        src += "(?:.*/)?"; // `**/x` — x at any depth
        i += 2;
      } else if (i + 2 === glob.length && src.endsWith("/")) {
        src = `${src.slice(0, -1)}(?:/.*)?`; // `dir/**` — dir itself and everything under it
        i += 1;
      } else {
        src += ".*";
        i += 1;
      }
    } else if (c === "*") src += "[^/]*";
    else if (c === "?") src += "[^/]";
    else src += c.replace(/[.+^${}()|[\]\\]/g, "\\$&");
  }
  re = new RegExp(`^${src}$`, process.platform === "win32" ? "i" : "");
  globCache.set(glob, re);
  return re;
}

export const matchesAny = (path, globs) => globs.some((g) => globToRegExp(g).test(path));

/** Repo-relative, forward-slash path, or `undefined` when the path is outside the repository. */
export function toRepoPath(root, p) {
  if (!p || typeof p !== "string") return undefined;
  let s = p.trim().replace(/^file:\/\/\/?/, "");
  s = decodeURIComponent(s);
  const abs = isAbsolute(s) ? s : resolve(root, s);
  const rel = relative(root, abs).replace(/\\/g, "/");
  if (!rel || rel.startsWith("..") || isAbsolute(rel)) return undefined;
  return rel;
}

