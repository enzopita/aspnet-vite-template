// git

export function git(args, opts = {}) {
  return execFileSync("git", args, {
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
    stdio: ["ignore", "pipe", opts.quiet ? "ignore" : "pipe"],
    cwd: opts.cwd,
  }).replace(/\s+$/, "");
}

export function tryGit(args, opts = {}) {
  try {
    return git(args, { ...opts, quiet: true });
  } catch {
    return undefined;
  }
}

export function repoRoot(cwd = process.cwd()) {
  return git(["rev-parse", "--show-toplevel"], { cwd });
}

export function currentBranch(cwd) {
  return tryGit(["symbolic-ref", "--quiet", "--short", "HEAD"], { cwd }) ?? "";
}

export function gitDir(cwd) {
  return resolve(cwd, git(["rev-parse", "--git-common-dir"], { cwd }));
}

