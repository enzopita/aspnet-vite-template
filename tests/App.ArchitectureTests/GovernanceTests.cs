        private static async Task<(int ExitCode, string Output)> RunDotnetAsync(string[] args)
        {
            var psi = new ProcessStartInfo("dotnet")
            {
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
                CreateNoWindow = true,
            };
            foreach (var a in args)
            {
                psi.ArgumentList.Add(a);
            }

            using var proc = Process.Start(psi) ?? throw new InvalidOperationException("Failed to start dotnet.");
            var stdoutTask = proc.StandardOutput.ReadToEndAsync();
            var stderrTask = proc.StandardError.ReadToEndAsync();
            await proc.WaitForExitAsync();
            var output = $"{await stdoutTask}\n{await stderrTask}";
            return (proc.ExitCode, output);
        }
