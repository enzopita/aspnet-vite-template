    public sealed record BuildResult(int ExitCode, string Output, IReadOnlyDictionary<int, string> SourceLines)
    {
        public static BuildResult Create(string csprojPath, int exitCode, string output)
        {
            var projDir = Path.GetDirectoryName(csprojPath) ?? throw new InvalidOperationException("Missing project directory.");
            var samplePath = Path.Combine(projDir, "Sample.cs");
            var lines = new Dictionary<int, string>();
            var rawLines = File.ReadAllLines(samplePath);
            for (var i = 0; i < rawLines.Length; i++)
            {
                lines[i + 1] = rawLines[i];
            }

            return new BuildResult(exitCode, output, lines);
        }

        public List<string> LinesForMethod(string methodName)
        {
            var matchingLineNumbers = SourceLines
                .Where(kv => kv.Value.Contains(methodName, StringComparison.Ordinal))
                .Select(kv => kv.Key)
                .ToHashSet();

            var result = new List<string>();
            foreach (var line in Output.Split('\n'))
            {
                foreach (var ln in matchingLineNumbers)
                {
                    if (line.Contains($"({ln},", StringComparison.Ordinal))
                    {
                        result.Add(line);
                        break;
                    }
                }
            }

            return result;
        }
    }

    private sealed class TempRepo : IDisposable
    {
        public string Root { get; } = Path.Combine(Path.GetTempPath(), $"app-gov-unit-{Guid.NewGuid():N}");

        private TempRepo() => Directory.CreateDirectory(Root);

        public static TempRepo Create() => new();

        public void Write(string relPath, string content)
        {
            var full = Path.Combine(Root, relPath.Replace('/', Path.DirectorySeparatorChar));
            var parent = Path.GetDirectoryName(full) ?? throw new InvalidOperationException("Missing parent directory.");
            Directory.CreateDirectory(parent);
            File.WriteAllText(full, content);
        }

        public void Dispose()
        {
            try
            {
                if (Directory.Exists(Root))
                {
                    Directory.Delete(Root, recursive: true);
                }
            }
            catch (IOException)
            {
            }
        }
    }
