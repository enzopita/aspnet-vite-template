/// <summary>Stateless checks over a repository tree, reused by both real-repo tests and synthetic negative tests.</summary>
internal static partial class GovernanceInspector
{
    private static readonly string[] SkipDirs =
    [
        ".git",
        "node_modules",
        "bin",
        "obj",
        "dist",
        "plano",
        ".vs",
        ".idea",
    ];

    private static readonly string[] SdkDefaultNoWarn = ["1701", "1702"];

    public static List<string> CheckCSharpDirectives(string root)
    {
        var allowlist = ReadAllowedSuppressions(root);
        var violations = new List<string>();

        foreach (var (full, rel) in EnumerateFiles(root, rel => (rel.StartsWith("src/", StringComparison.Ordinal) || rel.StartsWith("tests/", StringComparison.Ordinal)) && rel.EndsWith(".cs", StringComparison.Ordinal)))
        {
            var isMigration = IsValidMigrationCsFile(rel);
            var lines = File.ReadAllLines(full);
            for (var i = 0; i < lines.Length; i++)
            {
                var line = lines[i];
                if (IsAllowlisted(allowlist, rel, line))
                {
                    continue;
                }

                if (!isMigration && PragmaWarningDisableRegex().IsMatch(line))
                {
                    violations.Add($"{rel}:{i + 1}: pragma warning-disable directive is forbidden outside generated migrations.");
                }

                if (!isMigration && NullableDisableRegex().IsMatch(line))
                {
                    violations.Add($"{rel}:{i + 1}: nullable-disable directive is forbidden outside generated migrations.");
                }

                if (!isMigration && AutoGeneratedRegex().IsMatch(line))
                {
                    violations.Add($"{rel}:{i + 1}: auto-generated header is forbidden in hand-written files.");
                }

                if (SuppressMessageRegex().IsMatch(line))
                {
                    violations.Add($"{rel}:{i + 1}: SuppressMessage attribute is forbidden.");
                }
            }
        }

        return violations;
    }

    public static List<string> CheckProjectFiles(string root)
    {
        var approvedNoWarn = LoadNoWarnMap(root, out var allowlistErrors);
        var violations = new List<string>(allowlistErrors);

        foreach (var (full, rel) in EnumerateFiles(root, rel => (rel.StartsWith("src/", StringComparison.Ordinal) || rel.StartsWith("tests/", StringComparison.Ordinal)) && rel.EndsWith(".csproj", StringComparison.Ordinal)))
        {
            var text = File.ReadAllText(full);
            var projectName = Path.GetFileNameWithoutExtension(rel);

            if (ImportDirectoryBuildTargetsRegex().IsMatch(text))
            {
                violations.Add($"{rel}: ImportDirectoryBuildTargets is forbidden.");
            }

            if (ImportElementRegex().IsMatch(text))
            {
                violations.Add($"{rel}: extra <Import> inside .csproj is forbidden.");
            }

            if (CompileRemoveRegex().IsMatch(text))
            {
                violations.Add($"{rel}: <Compile Remove> is forbidden.");
            }

            var doc = XDocument.Load(full);
            var rootEl = doc.Root;
            if (rootEl is null)
            {
                continue;
            }

            foreach (var prop in rootEl.Elements("PropertyGroup").Elements())
            {
                var name = prop.Name.LocalName;
                var value = prop.Value.Trim();
                if (name.Equals("TreatWarningsAsErrors", StringComparison.Ordinal) && !value.Equals("true", StringComparison.OrdinalIgnoreCase))
                {
                    violations.Add($"{rel}: TreatWarningsAsErrors cannot be '{value}'.");
                }
                else if (name.Equals("CodeAnalysisTreatWarningsAsErrors", StringComparison.Ordinal) && !value.Equals("true", StringComparison.OrdinalIgnoreCase))
                {
                    violations.Add($"{rel}: CodeAnalysisTreatWarningsAsErrors cannot be '{value}'.");
                }
                else if (name.Equals("Nullable", StringComparison.Ordinal) && !value.Equals("enable", StringComparison.OrdinalIgnoreCase))
                {
                    violations.Add($"{rel}: Nullable cannot be '{value}'.");
                }
                else if (name is "RunAnalyzers" or "RunAnalyzersDuringBuild" or "EnableNETAnalyzers" or "EnforceCodeStyleInBuild" && !value.Equals("true", StringComparison.OrdinalIgnoreCase))
                {
                    violations.Add($"{rel}: {name} cannot be '{value}'.");
                }
                else if (name.Equals("AnalysisLevel", StringComparison.Ordinal) && !value.Equals("latest-recommended", StringComparison.OrdinalIgnoreCase))
                {
                    violations.Add($"{rel}: AnalysisLevel cannot be '{value}'.");
                }
                else if (name.StartsWith("AnalysisMode", StringComparison.Ordinal) && value.Length > 0)
                {
                    violations.Add($"{rel}: {name} override is forbidden.");
                }
                else if (name.Equals("WarningsNotAsErrors", StringComparison.Ordinal) && value.Length > 0)
                {
                    violations.Add($"{rel}: WarningsNotAsErrors is forbidden.");
                }
                else if (name.Equals("NoWarn", StringComparison.Ordinal))
                {
                    approvedNoWarn.TryGetValue(projectName, out var allowedCodes);
                    foreach (var code in value.Replace("$(NoWarn)", string.Empty, StringComparison.OrdinalIgnoreCase)
                                 .Split([';', ',', ' ', '\t', '\r', '\n'], StringSplitOptions.RemoveEmptyEntries))
                    {
                        if (!SdkDefaultNoWarn.Contains(code, StringComparer.OrdinalIgnoreCase) && (allowedCodes is null || !allowedCodes.Contains(code)))
                        {
                            violations.Add($"{rel}: unapproved NoWarn '{code}'.");
                        }
                    }
                }
            }
        }

        return violations;
    }

    public static List<string> CheckAnalyzerConfigFiles(string root)
    {
        var violations = new List<string>();
        var editorConfigs = new List<string>();

        foreach (var (_, rel) in EnumerateFiles(root, _ => true))
        {
            var fileName = Path.GetFileName(rel);
            if (fileName.Equals(".editorconfig", StringComparison.OrdinalIgnoreCase))
            {
                editorConfigs.Add(rel);
            }
            else if (fileName.EndsWith(".globalconfig", StringComparison.OrdinalIgnoreCase))
            {
                violations.Add($"{rel}: .globalconfig files are forbidden; keep analyzer config in root .editorconfig.");
            }
        }

        if (!editorConfigs.Contains(".editorconfig", StringComparer.Ordinal))
        {
            violations.Add("Missing root .editorconfig.");
        }

        foreach (var extra in editorConfigs.Where(p => !p.Equals(".editorconfig", StringComparison.Ordinal)))
        {
            violations.Add($"{extra}: nested .editorconfig is forbidden; keep a single .editorconfig at repository root.");
        }

        return violations;
    }

    public static List<string> CheckMigrations(string root)
    {
        var violations = new List<string>();
        foreach (var (_, rel) in EnumerateFiles(root, rel => rel.StartsWith("src/Modules/", StringComparison.Ordinal) && rel.Contains("/Persistence/Migrations/", StringComparison.Ordinal)))
        {
            var fileName = Path.GetFileName(rel);
            if (!MigrationFileNameRegex().IsMatch(fileName))
            {
                violations.Add($"{rel}: non-migration file inside Persistence/Migrations/.");
            }
        }

        return violations;
    }

    public static List<string> CheckTestFiles(string root)
    {
        var violations = new List<string>();
        foreach (var (full, rel) in EnumerateFiles(root, rel => rel.StartsWith("tests/", StringComparison.Ordinal) && rel.EndsWith(".cs", StringComparison.Ordinal)))
        {
            var lines = File.ReadAllLines(full);
            for (var i = 0; i < lines.Length; i++)
            {
                var line = lines[i];
                if (SkipAttributePropertyRegex().IsMatch(line))
                {
                    violations.Add($"{rel}:{i + 1}: SkipUnless/SkipWhen/Explicit in attribute is forbidden.");
                }

                if (IgnoreAttributeRegex().IsMatch(line))
                {
                    violations.Add($"{rel}:{i + 1}: Ignore attribute is forbidden.");
                }

                if (NullConditionalShouldRegex().IsMatch(line))
                {
                    violations.Add($"{rel}:{i + 1}: assertion behind '?.' is skipped when null.");
                }

                if (StatusCodeShouldNotBeRegex().IsMatch(line))
                {
                    violations.Add($"{rel}:{i + 1}: negative StatusCode assertion is too weak; assert the exact status code.");
                }

                if (NullForgivingRegex().IsMatch(line))
                {
                    violations.Add($"{rel}:{i + 1}: null-forgiving '!' hides potential nulls in tests.");
                }
            }
        }

        return violations;
    }

    public static List<string> CheckNoWarnAllowlist(string root)
    {
        _ = LoadNoWarnMap(root, out var errors);
        return errors;
    }

    private static Dictionary<string, HashSet<string>> LoadNoWarnMap(string root, out List<string> errors)
    {
        errors = [];
        var map = new Dictionary<string, HashSet<string>>(StringComparer.Ordinal);
        var path = Path.Combine(root, "governance", "nowarn.json");
        if (!File.Exists(path))
        {
            errors.Add("governance/nowarn.json is missing.");
            return map;
        }

        using var doc = JsonDocument.Parse(File.ReadAllText(path));
        if (!doc.RootElement.TryGetProperty("projects", out var projects) || projects.ValueKind != JsonValueKind.Object)
        {
            errors.Add("governance/nowarn.json must define a 'projects' object.");
            return map;
        }

        foreach (var proj in projects.EnumerateObject())
        {
            if (proj.Value.ValueKind != JsonValueKind.Object)
            {
                errors.Add($"governance/nowarn.json project '{proj.Name}' must map warning codes to metadata.");
                continue;
            }

            var codes = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            foreach (var code in proj.Value.EnumerateObject())
            {
                if (code.Value.ValueKind != JsonValueKind.Object
                    || !code.Value.TryGetProperty("reason", out var reason)
                    || string.IsNullOrWhiteSpace(reason.GetString())
                    || !code.Value.TryGetProperty("removeWhen", out var removeWhen)
                    || string.IsNullOrWhiteSpace(removeWhen.GetString()))
                {
                    errors.Add($"governance/nowarn.json entry '{proj.Name}.{code.Name}' must have non-empty 'reason' and 'removeWhen'.");
                    continue;
                }

                codes.Add(code.Name);
            }

            map[proj.Name] = codes;
        }

        return map;
    }

    private static List<(string RelativePath, string Substring)> ReadAllowedSuppressions(string root)
    {
        var path = Path.Combine(root, "governance", "allowed-suppressions.txt");
        if (!File.Exists(path))
        {
            return [];
        }

        var list = new List<(string, string)>();
        foreach (var raw in File.ReadAllLines(path))
        {
            var trimmed = raw.Trim();
            if (trimmed.Length == 0 || trimmed.StartsWith('#'))
            {
                continue;
            }

            var colon = trimmed.IndexOf(':', StringComparison.Ordinal);
            if (colon <= 0)
            {
                continue;
            }

            var file = trimmed[..colon].Trim();
            var rest = trimmed[(colon + 1)..];
            var commentIdx = rest.IndexOf(" #", StringComparison.Ordinal);
            var needle = (commentIdx >= 0 ? rest[..commentIdx] : rest).Trim();
            if (file.Length > 0 && needle.Length > 0)
            {
                list.Add((file, needle));
            }
        }

        return list;
    }

    private static bool IsAllowlisted(List<(string RelativePath, string Substring)> allowlist, string rel, string line) =>
        allowlist.Any(e => e.RelativePath.Equals(rel, StringComparison.Ordinal) && line.Contains(e.Substring, StringComparison.Ordinal));

    private static bool IsValidMigrationCsFile(string rel) =>
        rel.StartsWith("src/Modules/", StringComparison.Ordinal)
        && rel.Contains("/Persistence/Migrations/", StringComparison.Ordinal)
        && MigrationFileNameRegex().IsMatch(Path.GetFileName(rel));

    private static IEnumerable<(string FullPath, string RelativePath)> EnumerateFiles(string root, Func<string, bool> filter)
    {
        var pending = new Stack<string>();
        pending.Push(root);
        while (pending.Count > 0)
        {
            var dir = pending.Pop();
            foreach (var sub in Directory.EnumerateDirectories(dir))
            {
                if (SkipDirs.Contains(Path.GetFileName(sub), StringComparer.OrdinalIgnoreCase))
                {
                    continue;
                }

                pending.Push(sub);
            }

            foreach (var file in Directory.EnumerateFiles(dir))
            {
                var rel = Path.GetRelativePath(root, file).Replace('\\', '/');
                if (filter(rel))
                {
                    yield return (file, rel);
                }
            }
        }
    }

